// Writes src/commerce/installed.ts: one loader for every commerce connector
// package (@gifting/commerce-<name>) in this service's package.json
// dependencies. Runs before dev, build, typecheck and test, so installing a
// connector package is all it takes to make COMMERCE_CONNECTOR=<name> work;
// no code is edited by hand (plan: commerce-connectors.md).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const { dependencies = {} } = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const names = Object.keys(dependencies)
  .filter((dep) => /^@gifting\/commerce-[a-z0-9-]+$/.test(dep))
  .sort();

const lines = [
  "// Generated by scripts/connectors.mjs from package.json. Don't edit: add or",
  "// remove a @gifting/commerce-<name> dependency instead.",
  'import type { ConnectorFactory } from "@gifting/commerce";',
  "",
  "export const INSTALLED_CONNECTORS: Record<string, () => Promise<{ default: ConnectorFactory }>> = {",
  ...names.map((pkg) => `  ${JSON.stringify(pkg.slice("@gifting/commerce-".length))}: () => import(${JSON.stringify(pkg)}),`),
  "};",
  "",
];
const file = path.join(root, "src/commerce/installed.ts");
const next = lines.join("\n");
let current = "";
try {
  current = readFileSync(file, "utf8");
} catch {
  // first run
}
if (current !== next) writeFileSync(file, next);
